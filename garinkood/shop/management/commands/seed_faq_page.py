class Command(BaseCommand):
    help = 'ایجاد صفحه «سؤالات متداول» از روی رفتار واقعی سامانه'

    def add_arguments(self, parser):
        parser.add_argument('--force', action='store_true', help='بلوک‌های موجود را بازنویسی کن')
        parser.add_argument('--dry-run', action='store_true', help='فقط گزارش بده')

    def handle(self, *args, **options):
        verbosity = options.get('verbosity', 1)

        def say(message):
            if verbosity:
                self.stdout.write(message)

        page, created = SitePage.objects.get_or_create(
            slug='faq',
            defaults={
                'title': 'سؤالات متداول',
                'kind': SitePage.KIND_PAGE,
                'badge': 'راهنما',
                'hero_text': HERO,
                'seo_title': 'سؤالات متداول گرین کود | خرید، ارسال و بازگشت کالا',
                'seo_description': (
                    'پاسخ کوتاه به پرسش‌های رایج: خرید مهمان، قیمت و استعلام عمده، '
                    'پرداخت، زمان ارسال، لغو و بازگشت کالا، امتیاز وفاداری و غرفه‌داری.'
                ),
                'published': True,
            },
        )
        if not created and not options['force']:
            say('صفحه سؤالات متداول از قبل وجود دارد؛ برای بازنویسی بلوک‌ها --force را بفرستید.')
            return

        blocks = list(SitePageBlock.objects.filter(page=page))
        if blocks and not options['force']:
            say(f'{len(blocks)} بلوک موجود دست‌نخورده می‌ماند.')
            return
        if blocks and options['force'] and not options['dry_run']:
            SitePageBlock.objects.filter(page=page).delete()

        count = 0
        for position, (title, pairs) in enumerate(GROUPS):
            rows = '\n'.join(f'{question} | {answer}' for question, answer in pairs)
            if options['dry_run']:
                count += 1
                continue
            SitePageBlock.objects.create(
                page=page,
                block_type='faq',
                title=title,
                rows=rows,
                position=position,
            )
            count += 1

        if options['dry_run']:
            say(f'{count} گروه پرسش و پاسخ ثبت خواهد شد.')
            return
        say(f'صفحه سؤالات متداول با {count} گروه پرسش و پاسخ آماده شد.')
