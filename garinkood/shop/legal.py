class LegalDoc:
    """One legal document: what it is called, where it is linked from, and the
    text that ships with the code."""

    def __init__(self, slug, title, group, summary, icon, sections):
        self.slug = slug
        self.title = title
        self.group = group
        self.summary = summary
        self.icon = icon
        self.sections = sections

    @property
    def heading(self):
        """The nav label: shorter than the H1, same meaning."""
        return SHORT_TITLES.get(self.slug, self.title)


