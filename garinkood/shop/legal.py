"""The site's legal documents: one registry, two possible sources of text.

Every document lives here as the text that ships with the code, so a fresh
deployment never shows an empty legal page, and the same slug can be taken over
by a published :class:`~shop.models.SitePage` whose blocks replace the sections
from the admin panel. Nothing else in the project decides what the legal terms
are; the checkout acceptance, the footer, the sitemap and the ``/legal`` pages
all read from this module, so the sentence a buyer agrees to and the sentence
they can later read are the same sentence.

Numbers quoted in these documents are read from the code that implements them
(``rewards``, ``settlements``, the desk hours) rather than written again here.
A policy page that states a limit the software does not enforce is worse than no
page at all, so where a figure is editable the text says where to look instead
of repeating a value that will drift.
"""

