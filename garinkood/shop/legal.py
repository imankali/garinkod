BY_SLUG = {doc.slug: doc for doc in DOCUMENTS}

# URLs that existed before this registry and are linked from the footer, the
# sitemap and old e-mails. They render the same page as the canonical address.
LEGACY_ROUTES = {'/privacy': 'privacy', '/terms': 'terms', '/returns': 'returns'}


def documents() -> list[LegalDoc]:
    return list(DOCUMENTS)


def get(slug: str) -> LegalDoc | None:
    return BY_SLUG.get((slug or '').strip())


def _override(slug: str):
    """The published admin page for this document, if there is one."""
    return (
        SitePage.objects.filter(slug=slug, published=True, kind=SitePage.KIND_PAGE)
        .prefetch_related('blocks')
        .first()
    )


def _page_blocks(page: SitePage) -> list[dict]:
    """Blocks the renderer understands, in the admin's own order.

    Legal pages are read as titled passages; a ``bullets`` block becomes a list,
    a ``quote`` a highlighted line, and a table block is skipped rather than
    flattened into prose that would read as nonsense.
    """
    blocks = []
    for block in page.blocks.all():
        if block.block_type in ('spec_table', 'price_table'):
            continue
        blocks.append(
            {
                'id': block.id,
                'type': block.block_type,
                'title': block.title,
                'text': block.text,
            }
        )
    return blocks


def payload(doc: LegalDoc, *, include_sections: bool = True) -> dict:
    """One document as the frontend renders it.

    ``source`` tells the reader whether they are looking at the text that ships
    with the code or at what the team published in the admin panel, and
    ``updated_at`` is only claimed when a real page edit backs it.
    """
    page = _override(doc.slug)
    blocks = _page_blocks(page) if page else []
    data = {
        'slug': doc.slug,
        'title': (page.title if page and page.title else doc.title),
        'short_title': SHORT_TITLES.get(doc.slug, doc.title),
        'group': doc.group,
        'group_label': GROUP_LABELS.get(doc.group, ''),
        'icon': doc.icon,
        'summary': (page.hero_text if page and page.hero_text else doc.summary),
        'source': 'page' if blocks else 'code',
        'updated_at': page.updated_at.isoformat() if page else None,
        'url': f'/legal/{doc.slug}',
    }
    if include_sections:
        data['blocks'] = blocks
        data['sections'] = [] if blocks else [{'title': head, 'body': body} for head, body in doc.sections]
    return data


